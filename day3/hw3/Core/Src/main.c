static void rs_send(uint8_t comm_type, const uint8_t data[8])
{
  CAN_TxHeaderTypeDef header;
  uint32_t mailbox;

  header.ExtId = ((uint32_t)comm_type << 24) | ((uint32_t)HOST_ID << 8) | motor_id;
  header.IDE = CAN_ID_EXT;
  header.RTR = CAN_RTR_DATA;
  header.DLC = 8;
  header.TransmitGlobalTime = DISABLE;

  uint32_t start = HAL_GetTick();
  while (HAL_CAN_GetTxMailboxesFreeLevel(&hcan1) == 0)
  {
    if (HAL_GetTick() - start > 10) return;   // 메일박스가 안 비면 포기
  }
  HAL_CAN_AddTxMessage(&hcan1, &header, (uint8_t *)data, &mailbox);
}

// 통신 타입 0(장치 ID 요청)을 ID 1~127에 차례로 보내고 응답한 모터의 ID를 찾는다
static void rs_scan(void)
{
  uint8_t zero[8] = {0};
  CAN_RxHeaderTypeDef rx_header;
  uint8_t rx_data[8];

  for (uint16_t n = 0; n < 127; n++)
  {
    motor_id = (n == 0) ? 0x7F : n;   // 0x7F 먼저, 그다음 1~126
    rs_send(0, zero);
    HAL_Delay(3);
    while (HAL_CAN_GetRxFifoFillLevel(&hcan1, CAN_RX_FIFO0) > 0)
    {
      HAL_CAN_GetRxMessage(&hcan1, CAN_RX_FIFO0, &rx_header, rx_data);
      if (((rx_header.ExtId >> 24) & 0x1F) == 0)   // 타입 0 응답
      {
        motor_id = (rx_header.ExtId >> 8) & 0xFF;  // bit15~8 = 모터 CAN ID
        return;
      }
    }
  }
  motor_id = MOTOR_ID;   // 못 찾음
}

static void rs_write_u8(uint16_t index, uint8_t value)
{
  uint8_t data[8] = {0};
  memcpy(&data[0], &index, 2);   // Byte0~1: index (little endian)
  data[4] = value;               // Byte4~7: 값
  rs_send(COMM_WRITE, data);
}

static void rs_write_float(uint16_t index, float value)
{
  uint8_t data[8] = {0};
  memcpy(&data[0], &index, 2);
  memcpy(&data[4], &value, 4);   // float, little endian
  rs_send(COMM_WRITE, data);
}
