static uint16_t dxl_update_crc(uint16_t crc_accum, const uint8_t *buf, uint16_t len)
{
  for (uint16_t j = 0; j < len; j++) {
    uint16_t i = ((crc_accum >> 8) ^ buf[j]) & 0xFF;
    crc_accum = (crc_accum << 8) ^ dxl_crc_table[i];
  }
  return crc_accum;
}

// buf를 그대로 USART3로 내보낸다. DMA 없이 폴링으로, 한 바이트씩 TXE(송신
// 레지스터 빈 상태)를 기다렸다가 넣고, 마지막에는 TC(전송 완료)까지 기다린다.
static void usart3_send(const uint8_t *buf, uint16_t len)
{
  for (uint16_t i = 0; i < len; i++) {
    while (!LL_USART_IsActiveFlag_TXE(USART3));
    LL_USART_TransmitData8(USART3, buf[i]);
  }
  while (!LL_USART_IsActiveFlag_TC(USART3));
}

// Write Instruction Packet(0x03)을 만들어서 보낸다.
// Instruction Packet 구조: Header(3) Reserved(1) ID(1) Len_L Len_H Instruction Param... CRC_L CRC_H
// Write의 Param은 [주소_L, 주소_H, 쓸 데이터...] 순서다.
// CRC는 Header 포함 CRC 필드 직전까지 전체를 대상으로 계산한다.
static void dxl_write(uint8_t id, uint16_t addr, const uint8_t *data, uint16_t data_len)
{
  uint8_t pkt[16];
  uint16_t n = 0;

  uint16_t param_len = 2 + data_len;          // 주소 2바이트 + 데이터
  uint16_t length     = 1 + param_len + 2;    // Instruction(1) + Param + CRC(2)

  pkt[n++] = 0xFF; pkt[n++] = 0xFF; pkt[n++] = 0xFD; // Header
  pkt[n++] = 0x00;                                    // Reserved
  pkt[n++] = id;
  pkt[n++] = length & 0xFF;
  pkt[n++] = (length >> 8) & 0xFF;
  pkt[n++] = DXL_INST_WRITE;
  pkt[n++] = addr & 0xFF;
  pkt[n++] = (addr >> 8) & 0xFF;
  for (uint16_t i = 0; i < data_len; i++) {
    pkt[n++] = data[i];
  }

  uint16_t crc = dxl_update_crc(0, pkt, n);
  pkt[n++] = crc & 0xFF;
  pkt[n++] = (crc >> 8) & 0xFF;

  usart3_send(pkt, n);
}

static void dxl_set_torque(uint8_t id, uint8_t on)
{
  dxl_write(id, DXL_ADDR_TORQUE_ENABLE, &on, 1);
}

static void dxl_set_goal_position(uint8_t id, uint16_t raw)
{
  uint8_t data[4] = {
    (uint8_t)( raw       & 0xFF),
    (uint8_t)((raw >> 8) & 0xFF),
    0, 0, // Goal Position은 4바이트지만 0~4095 범위라 상위 2바이트는 항상 0
  };
  dxl_write(id, DXL_ADDR_GOAL_POSITION, data, 4);
}

