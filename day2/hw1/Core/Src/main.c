/* USER CODE BEGIN 4 */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
  // TIM6은 100us마다 이 콜백을 호출한다. 여기서 직접 시간을 세는 대신
  // "몇 번 호출됐는지"를 카운터로 누적해서, 카운터가 TOGGLE_TICKS(5000회
  // = 0.5초)에 도달할 때만 실제 GPIO를 건드린다.
  if (htim->Instance == TIM6) {
    // 1. PD2: 0.5초마다 토글 (켜짐 0.5초 + 꺼짐 0.5초 = 1초 주기)
    if (++pd2_tick >= TOGGLE_TICKS) {
      pd2_tick = 0;          // 카운터를 0부터 다시 셈
      HAL_GPIO_TogglePin(GPIOD, GPIO_PIN_2);
    }

    // 2. 스위치별 LED: 4쌍을 순서대로 검사
    for (int i = 0; i < 4; i++) {
      SwLed_t *s = &sw_leds[i];

      if (HAL_GPIO_ReadPin(GPIOB, s->sw_pin) == SW_ACTIVE) {
        // 스위치가 눌려 있는 동안: 카운터를 계속 누적하다가
        // 0.5초치가 쌓이면 LED를 반대 상태로 바꾸고 카운터 리셋
        if (++s->tick >= TOGGLE_TICKS) {
          s->tick = 0;
          s->on = !s->on;
          HAL_GPIO_WritePin(GPIOB, s->led_pin, s->on ? LED_ON_LEVEL : LED_OFF_LEVEL);
        }
      } else {
        // 스위치를 뗀 상태: LED를 끄고 카운터도 리셋해서,
        // 다음에 다시 누르면 항상 꺼진 상태에서 새로 깜빡이기 시작하게 한다
        s->tick = 0;
        s->on = 0;
        HAL_GPIO_WritePin(GPIOB, s->led_pin, LED_OFF_LEVEL);
      }
    }
  }
}
